package main

import (
	"bytes"
	"encoding/json"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// specIn copies the design example into a fresh directory, optionally with CRLF line endings.
func specIn(t *testing.T, crlf bool) string {
	t.Helper()
	src, err := os.ReadFile(filepath.Join("testdata", "valid", "design-example.yml"))
	if err != nil {
		t.Fatal(err)
	}
	if crlf {
		src = bytes.ReplaceAll(src, []byte("\n"), []byte("\r\n"))
	}
	path := filepath.Join(t.TempDir(), "pinfold.yml")
	if err := os.WriteFile(path, src, 0o600); err != nil {
		t.Fatal(err)
	}
	return path
}

func runOK(t *testing.T, want int, args ...string) (string, string) {
	t.Helper()
	var stdout, stderr bytes.Buffer
	if code := run(args, &stdout, &stderr); code != want {
		t.Fatalf("%v: exit %d, want %d\nstdout: %s\nstderr: %s", args, code, want, stdout.String(), stderr.String())
	}
	return stdout.String(), stderr.String()
}

func readOut(t *testing.T, spec, name string) string {
	t.Helper()
	b, err := os.ReadFile(filepath.Join(filepath.Dir(spec), ".github", "workflows", name))
	if err != nil {
		t.Fatal(err)
	}
	return string(b)
}

func TestCompile(t *testing.T) {
	spec := specIn(t, false)
	out, _ := runOK(t, 0, "compile", spec)
	if !strings.Contains(out, "pinfold-release.yml") || !strings.Contains(out, "pinfold-triage.yml") {
		t.Errorf("compile output = %q", out)
	}
	release := readOut(t, spec, "pinfold-release.yml")
	if !strings.HasPrefix(release, "# Generated by pinfold from pinfold.yml.") {
		t.Errorf("missing header:\n%s", release)
	}

	// Up to date → 0; edited → 2; deleted → 2.
	runOK(t, 0, "compile", "--check", spec)
	p := filepath.Join(filepath.Dir(spec), ".github", "workflows", "pinfold-release.yml")
	if err := os.WriteFile(p, []byte(release+"# edited\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if out, _ := runOK(t, 2, "compile", "--check", spec); !strings.Contains(out, "out of date: .github/workflows/pinfold-release.yml") {
		t.Errorf("drift output = %q", out)
	}
	if err := os.Remove(p); err != nil {
		t.Fatal(err)
	}
	if out, _ := runOK(t, 2, "compile", "--check", spec); !strings.Contains(out, "(missing)") {
		t.Errorf("missing-file output = %q", out)
	}
}

func TestCompileIsDeterministicAcrossLineEndings(t *testing.T) {
	lf, crlf := specIn(t, false), specIn(t, true)
	runOK(t, 0, "compile", lf)
	runOK(t, 0, "compile", crlf)
	for _, name := range []string{"pinfold-release.yml", "pinfold-triage.yml"} {
		a, b := readOut(t, lf, name), readOut(t, crlf, name)
		if a != b {
			t.Errorf("%s differs between LF and CRLF specs", name)
		}
		if strings.Contains(a, "\r") {
			t.Errorf("%s contains CR", name)
		}
	}
	runOK(t, 0, "compile", lf)
	if again := readOut(t, lf, "pinfold-release.yml"); again != readOut(t, crlf, "pinfold-release.yml") {
		t.Error("recompiling changed the output")
	}
}

func TestCompileRejectsInvalidSpecAndWritesNothing(t *testing.T) {
	dir := t.TempDir()
	src, _ := os.ReadFile(filepath.Join("testdata", "malformed", "31-needs-cycle.yml"))
	spec := filepath.Join(dir, "pinfold.yml")
	if err := os.WriteFile(spec, src, 0o600); err != nil {
		t.Fatal(err)
	}
	_, errOut := runOK(t, 1, "compile", spec)
	if !strings.Contains(errOut, "PF126") {
		t.Errorf("stderr = %q", errOut)
	}
	if _, err := os.Stat(filepath.Join(dir, ".github")); !os.IsNotExist(err) {
		t.Error("compile wrote files for an invalid spec")
	}
}

func TestIR(t *testing.T) {
	out, _ := runOK(t, 0, "ir", specIn(t, false))
	var p struct{ Workflows []struct{ ID string } }
	if err := json.Unmarshal([]byte(out), &p); err != nil {
		t.Fatal(err)
	}
	if len(p.Workflows) != 2 || p.Workflows[0].ID != "release" {
		t.Errorf("IR workflows = %+v", p.Workflows)
	}
	runOK(t, 2, "ir", "a", "b")
	runOK(t, 2, "compile", "--bogus")
}
