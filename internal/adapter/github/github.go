func valueExpr(v ir.Value) string {
	switch v.Kind {
	case spec.Context:
		return "${{ " + contextExprs[v.Text] + " }}"
	case spec.Secret:
		return "${{ secrets." + v.Text + " }}"
	case spec.Var:
		return "${{ vars." + v.Text + " }}"
	case spec.Output:
		job, out, _ := strings.Cut(v.Text, ".")
		return "${{ needs." + job + ".outputs." + out + " }}"
	default:
		return v.Text
	}
}

func strSeq(vals []string) emit.Seq {
	out := make(emit.Seq, len(vals))
	for i, v := range vals {
		out[i] = emit.Str(v)
	}
	return out
}

// ephemeralStamp is the header line for a job whose spec asserts a fresh
// runner per job; the verifier requires it (security audit D1).
func ephemeralStamp(job string) string {
	return "pinfold:ephemeral_runner: job " + job + " relies on the spec's assertion that its runner is a fresh machine for every job."
}
