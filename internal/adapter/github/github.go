// Generated-step marker (design §5): the verifier uses it to tell compiler
// steps from user steps.
const generatedMarker = "pinfold:generated "

// Actions the adapter generates, pinned to peeled commit SHAs (checked
// 2026-10-30 with git ls-remote). The lock (M4) takes over pinning user actions.
var generatedActions = map[string]struct{ ref, tag string }{
	"checkout": {"actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1", "v7.0.1"},
	"upload":   {"actions/upload-artifact@cf430e030ddbb5b0abf93d22962f4752f3646cd9", "v7.0.2"},
	"download": {"actions/download-artifact@9000827ccba6bdab643e8b6fd33ac0654aef8333", "v8.0.2"},
	"script":   {"actions/github-script@3a2844b7e9c422d3c10d287c895573f7108da1b3", "v9.0.0"},
}

// File is one generated workflow.
type File struct {
	Path    string
	Content string
}

// Compile lowers every workflow. specHash identifies the source spec in the header.
func Compile(p *ir.Program, specFile, specHash string) []File {
	var out []File
	for _, w := range p.Workflows {
		out = append(out, File{
			Path:    ".github/workflows/pinfold-" + w.ID + ".yml",
			Content: emit.Document(header(w, specFile, specHash), workflow(w)),
		})
	}
	return out
}

func header(w *ir.Workflow, specFile, specHash string) []string {
	h := []string{
		fmt.Sprintf("Generated by pinfold from %s. Do not edit: change the spec and run \"pinfold compile\".", specFile),
		"pinfold:spec-sha256 " + specHash,
	}
	if w.UnsafeRun {
		h = append(h, "pinfold:unsafe_run: this workflow opted out of Pinfold's guarantees.")
	}
	for _, j := range w.Jobs {
		if j.EphemeralRunner {
			h = append(h, ephemeralStamp(j.Name))
		}
	}
	return h
}

func workflow(w *ir.Workflow) emit.Map {
	jobs := emit.Map{}
	for _, j := range w.Jobs {
		jobs = append(jobs, emit.Pair{Key: j.Name, Value: job(w, j)})
	}
	return emit.Map{
		{Key: "name", Value: emit.Str("pinfold " + w.ID)},
		{Key: "on", Value: triggers(w.Triggers)},
		{Key: "permissions", Value: emit.Empty{}},
		{Key: "jobs", Value: jobs},
	}
}

func triggers(ts []*spec.Trigger) emit.Map {
	out := emit.Map{}
	for _, t := range ts {
		switch t.Event {
		case "manual":
			out = append(out, emit.Pair{Key: "workflow_dispatch", Value: emit.Empty{}})
		case "schedule":
			var crons emit.Seq
			for _, c := range t.Crons {
				crons = append(crons, emit.Map{{Key: "cron", Value: emit.Str(c)}})
			}
			out = append(out, emit.Pair{Key: "schedule", Value: crons})
		default:
			cfg := emit.Map{}
			for _, f := range []struct {
				key  string
				vals []string
			}{{"types", t.Types}, {"branches", t.Branches}, {"tags", t.Tags}, {"paths", t.Paths}} {
				if len(f.vals) > 0 {
					cfg = append(cfg, emit.Pair{Key: f.key, Value: strSeq(f.vals)})
				}
			}
			out = append(out, emit.Pair{Key: t.Event, Value: cfg})
		}
	}
	return out
}

func job(w *ir.Workflow, j *ir.Job) emit.Map {
	m := emit.Map{{Key: "name", Value: emit.Str(j.Name)}}
	if needs := jobNeeds(j); len(needs) > 0 {
		m = append(m, emit.Pair{Key: "needs", Value: strSeq(needs)})
	}
	if j.If != nil {
		if expr := condition(j.If); expr != "" {
			m = append(m, emit.Pair{Key: "if", Value: emit.Str(expr)})
		}
	}
	m = append(m, emit.Pair{Key: "runs-on", Value: emit.Str(j.Runner)})
	if j.Environment != "" {
		m = append(m, emit.Pair{Key: "environment", Value: emit.Str(j.Environment)})
	}
	m = append(m, emit.Pair{Key: "permissions", Value: permissions(j.Capabilities)})
	if j.TimeoutMinutes > 0 {
		m = append(m, emit.Pair{Key: "timeout-minutes", Value: emit.Int(j.TimeoutMinutes)})
	}
	if j.Concurrency != nil {
		m = append(m, emit.Pair{Key: "concurrency", Value: emit.Map{
			{Key: "group", Value: emit.Str(j.Concurrency.Group)},
			{Key: "cancel-in-progress", Value: emit.Bool(j.Concurrency.CancelInProgress)},
		}})
	}
	if len(j.Produces) > 0 {
		outs := emit.Map{}
		for _, a := range j.Produces {
			for _, f := range []string{"id", "digest"} {
				outs = append(outs, emit.Pair{Key: "pinfold_" + a.Name + "_" + f, Value: emit.Str("${{ steps.pinfold_upload_" + a.Name + ".outputs.artifact-" + f + " }}")})
			}
		}
		m = append(m, emit.Pair{Key: "outputs", Value: outs})
	}
	m = append(m, emit.Pair{Key: "steps", Value: steps(w, j)})
	return m
}

// jobNeeds returns the declared needs plus every job this one consumes from:
// GitHub's needs context only covers direct dependencies.
func jobNeeds(j *ir.Job) []string {
	needs := slices.Clone(j.Needs)
	for _, c := range j.Consumes {
		if !slices.Contains(needs, c.From.Name) {
			needs = append(needs, c.From.Name)
		}
	}
	return needs
}

// permissions maps capabilities back to scopes; an empty set is {}. Each scope
// carries a comment saying why it's granted.
func permissions(caps []ir.Capability) emit.Node {
	scopes := map[string]string{}
	why := map[string][]string{}
	for scope, res := range ir.ScopeResources {
		for _, c := range caps {
			if c.Resource != res {
				continue
			}
			if scopes[scope] == "" || c.Access == ir.Write {
				scopes[scope] = string(c.Access)
			}
			reason := "declared in the spec"
			if c.Source != "declared" {
				reason = "needed by " + c.Source
			}
			if !slices.Contains(why[scope], reason) {
				why[scope] = append(why[scope], reason)
			}
		}
	}
	if len(scopes) == 0 {
		return emit.Empty{}
	}
	keys := make([]string, 0, len(scopes))
	for k := range scopes {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	m := emit.Map{}
	for _, k := range keys {
		sort.Strings(why[k])
		m = append(m, emit.Pair{Key: k, Value: emit.Str(scopes[k]), Comment: strings.Join(why[k], "; ")})
	}
	return m
}

func steps(w *ir.Workflow, j *ir.Job) emit.Seq {
	var out emit.Seq
	gated := hasMaintainer(j.If)
	if gated {
		out = append(out, gateStep(w, j))
	}
	for _, c := range j.Consumes {
		dl := generatedActions["download"]
		out = append(out, guard(gated, bindStep(j, c)))
		out = append(out, guard(gated, emit.Map{
			{Key: "name", Value: emit.Str("pinfold: download " + c.Name), Comment: generatedMarker + j.ID + "/consume-" + c.Name},
			{Key: "uses", Value: emit.Str(dl.ref), Comment: dl.tag},
			{Key: "with", Value: emit.Map{
				{Key: "artifact-ids", Value: emit.Str("${{ steps." + bindID(c.Name) + ".outputs.id }}")},
				{Key: "path", Value: emit.Str(c.To)},
				{Key: "digest-mismatch", Value: emit.Str("error")},
			}},
		}))
	}
	for _, s := range j.Steps {
		out = append(out, guard(gated, step(w, j, s)))
	}
	for _, a := range j.Produces {
		up := generatedActions["upload"]
		out = append(out, guard(gated, emit.Map{
			{Key: "name", Value: emit.Str("pinfold: upload " + a.Name), Comment: generatedMarker + j.ID + "/produce-" + a.Name},
			{Key: "id", Value: emit.Str("pinfold_upload_" + a.Name)},
			{Key: "uses", Value: emit.Str(up.ref), Comment: up.tag},
			{Key: "with", Value: emit.Map{
				{Key: "name", Value: emit.Str(a.Name)},
				{Key: "path", Value: emit.Str(a.Path)},
				{Key: "if-no-files-found", Value: emit.Str("error")},
			}},
		}))
	}
	return out
}

func step(w *ir.Workflow, j *ir.Job, s *ir.Step) emit.Map {
	var m emit.Map
	if s.Name != "" {
		m = append(m, emit.Pair{Key: "name", Value: emit.Str(s.Name)})
	}
	switch s.Kind {
	case ir.Checkout:
		co := generatedActions["checkout"]
		if len(m) == 0 {
			m = append(m, emit.Pair{Key: "name", Value: emit.Str("pinfold: checkout")})
		}
		m[0].Comment = generatedMarker + s.ID
		m = append(m,
			emit.Pair{Key: "uses", Value: emit.Str(co.ref), Comment: co.tag},
			emit.Pair{Key: "with", Value: emit.Map{{Key: "persist-credentials", Value: emit.Bool(false)}}},
		)
	case ir.Run:
		if len(s.Env) > 0 {
			m = append(m, emit.Pair{Key: "env", Value: values(s.Env)})
		}
		m = append(m, emit.Pair{Key: "run", Value: emit.Str(s.Run)})
	case ir.Uses:
		if e, reviewed, _ := registry.Lookup(s.Uses); e != nil && reviewed && e.Container != nil {
			return containerStep(s, e)
		}
		m = append(m, emit.Pair{Key: "uses", Value: emit.Str(s.Uses), Comment: "pinfold:unlocked (pinned by the lock from milestone M4)"})
		if len(s.With) > 0 {
			m = append(m, emit.Pair{Key: "with", Value: values(s.With)})
		}
	case ir.DoEffect:
		return effectStep(w, j, s)
	}
	return m
}

// containerStep runs an action's published image pinned by digest instead of
// the action itself (D-035). Inputs reach the image as INPUT_* environment
// variables, with the action's defaults filled in; the zones pass has already
// rejected inputs the registry doesn't map (PF306). Every mapped input is set,
// empty if it has no default, as GitHub does for a real action: the PyPI
// image's script runs with set -u and fails on an unset INPUT_PASSWORD.
func containerStep(s *ir.Step, e *registry.Entry) emit.Map {
	c := e.Container
	name := s.Name
	if name == "" {
		name = "pinfold: " + strings.SplitN(s.Uses, "@", 2)[0] + " (pinned container)"
	}
	env := map[string]ir.Value{}
	for _, ci := range c.Inputs {
		env[ci.Env] = ir.Value{Kind: spec.Literal, Text: ci.Default}
	}
	for k, v := range s.With {
		env[c.Inputs[k].Env] = v
	}
	return emit.Map{
		{Key: "name", Value: emit.Str(name), Comment: generatedMarker + s.ID},
		{Key: "uses", Value: emit.Str("docker://" + c.Ref()), Comment: s.Uses + " (" + c.Tag + ")"},
		{Key: "env", Value: values(env)},
	}
}

func values(vs map[string]ir.Value) emit.Map {
	keys := make([]string, 0, len(vs))
	for k := range vs {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	m := emit.Map{}
	for _, k := range keys {
		m = append(m, emit.Pair{Key: k, Value: emit.Str(valueExpr(vs[k]))})
	}
	return m
}

