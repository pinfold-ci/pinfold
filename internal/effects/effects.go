// Package effects holds the compiler-generated scripts for effects (design §5):
// each effect becomes one pinned actions/github-script step whose script is a
// literal, with every input read from the environment.
package effects

import (
	"embed"
	"fmt"
	"regexp"
	"slices"
	"sort"
)

//go:embed js/sanitize.js js/common.js js/comment.js js/labels.js js/commit_status.js js/release.js js/gate.js js/bind.js
var files embed.FS

// Sanitizer is the JavaScript sanitiser inlined into every effect script.
var Sanitizer = mustRead("sanitize.js")

// bodies maps each effect to the script file that implements it.
var bodies = map[string]string{
	"comment":       "comment.js",
	"add_labels":    "labels.js",
	"remove_labels": "labels.js",
	"commit_status": "commit_status.js",
	"release":       "release.js",
	Gate:            "gate.js",
	Bind:            "bind.js",
}

// Bind is the pseudo-effect name of the artifact binding step.
const Bind = "artifact_bind"

// Gate is the pseudo-effect name of the maintainer gate step.
const Gate = "maintainer_gate"

func mustRead(name string) string {
	b, err := files.ReadFile("js/" + name)
	if err != nil {
		panic(err)
	}
	return string(b)
}

// Script returns the complete, literal github-script source for an effect.
func Script(effect string) (string, error) {
	body, ok := bodies[effect]
	if !ok {
		return "", fmt.Errorf("unknown effect %q", effect)
	}
	return "// Generated by pinfold (effect " + effect + "). Do not edit.\n" +
		Sanitizer + mustRead("common.js") + mustRead(body), nil
}

// Scripts returns every effect's script by effect name, for the verifier.
func Scripts() map[string]string {
	out := map[string]string{}
	names := make([]string, 0, len(bodies))
	for n := range bodies {
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		s, _ := Script(n)
		out[n] = s
	}
	return out
}

var placeholderRE = regexp.MustCompile(`\{\{\s*([a-z_.]+)\s*\}\}`)

// Placeholders returns the distinct {{ name }} placeholders in a comment body, in order.
func Placeholders(body string) []string {
	var out []string
	for _, m := range placeholderRE.FindAllStringSubmatch(body, -1) {
		if !slices.Contains(out, m[1]) {
			out = append(out, m[1])
		}
	}
	return out
}
