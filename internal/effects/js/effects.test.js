test('commit_status: requires a full SHA and a valid state', async () => {
  await assert.rejects(run('commit_status', { T_SHA: 'abc', PINFOLD_STATE: 'success' }), /40-character/);
  await assert.rejects(run('commit_status', { PINFOLD_SHA: 'a'.repeat(40), PINFOLD_STATE: 'ok' }), /invalid commit status state/);
  const { calls } = await run('commit_status', { PINFOLD_SHA: 'a'.repeat(40), PINFOLD_STATE: 'success', PINFOLD_CONTEXT: 'ci', PINFOLD_DESCRIPTION: 'line1\nline2\u0000' });
  assert.strictEqual(calls[0][1].description, 'line1 line2');
});

