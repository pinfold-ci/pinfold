test('maintainer gate: fails closed', async () => {
  const api = { getCollaboratorPermissionLevel: () => ({ status: 200, data: { role_name: 'admin' } }) };
  // A re-run by someone else.
  assert.strictEqual((await run('maintainer_gate', { T_ACTOR: 'octo', T_TRIGGERING_ACTOR: 'mallory' }, api)).outputs.ok, 'false');
  // Bots and apps.
  assert.strictEqual((await run('maintainer_gate', { T_ACTOR: 'dependabot[bot]', T_TRIGGERING_ACTOR: 'dependabot[bot]' }, api)).outputs.ok, 'false');
  assert.strictEqual((await run('maintainer_gate', { T_ACTOR: 'octo', T_TRIGGERING_ACTOR: 'octo' }, api, [], { sender: { type: 'Bot' } })).outputs.ok, 'false');
  // Lookup errors (404 for non-collaborators, anything else).
  const err = (status) => ({ getCollaboratorPermissionLevel: () => { const e = new Error('x'); e.status = status; throw e; } });
  assert.strictEqual((await run('maintainer_gate', { T_ACTOR: 'octo', T_TRIGGERING_ACTOR: 'octo' }, err(404))).outputs.ok, 'false');
  assert.strictEqual((await run('maintainer_gate', { T_ACTOR: 'octo', T_TRIGGERING_ACTOR: 'octo' }, err(500))).outputs.ok, 'false');
  // Missing actor.
  assert.strictEqual((await run('maintainer_gate', {}, api)).outputs.ok, 'false');
});

// #64 and both audits: on a comment event the gate passes only for a new
// comment written by the user who triggered the run. Otherwise a maintainer
// deleting or editing someone else's "/label ..." comment would run the job
// as the maintainer on that person's text.
test('maintainer gate: comment events need a new comment by the actor', async () => {
  const api = { getCollaboratorPermissionLevel: () => ({ status: 200, data: { role_name: 'admin' } }) };
  const env = { T_ACTOR: 'octo', T_TRIGGERING_ACTOR: 'octo' };
  const ev = (action, author) => ({ sender: { type: 'User' }, action, comment: { user: { login: author } } });
  assert.strictEqual((await run('maintainer_gate', env, api, [], ev('created', 'octo'))).outputs.ok, 'true');
  assert.strictEqual((await run('maintainer_gate', env, api, [], ev('created', 'Octo'))).outputs.ok, 'true', 'logins compare without case');
  assert.strictEqual((await run('maintainer_gate', env, api, [], ev('deleted', 'mallory'))).outputs.ok, 'false', 'deleted');
  assert.strictEqual((await run('maintainer_gate', env, api, [], ev('edited', 'mallory'))).outputs.ok, 'false', 'edited, other author');
  assert.strictEqual((await run('maintainer_gate', env, api, [], ev('edited', 'octo'))).outputs.ok, 'false', 'edited, own comment');
  assert.strictEqual((await run('maintainer_gate', env, api, [], ev('created', 'mallory'))).outputs.ok, 'false', 'someone else\'s comment');
  assert.strictEqual((await run('maintainer_gate', env, api, [], { sender: { type: 'User' }, action: 'created', comment: {} })).outputs.ok, 'false', 'no author');
});

// #64: the same holds for issues, pull requests, reviews and discussions: a
// maintainer labelling or reopening someone else's issue must not pass.
test('maintainer gate: other content events need new content by the actor', async () => {
  const api = { getCollaboratorPermissionLevel: () => ({ status: 200, data: { role_name: 'admin' } }) };
  const env = { T_ACTOR: 'octo', T_TRIGGERING_ACTOR: 'octo' };
  const ev = (key, action, author, extra = {}) => ({ sender: { type: 'User' }, action, [key]: { user: { login: author } }, ...extra });
  const ok = async (p) => (await run('maintainer_gate', env, api, [], p)).outputs.ok;
  assert.strictEqual(await ok(ev('issue', 'opened', 'octo')), 'true', 'new issue');
  assert.strictEqual(await ok(ev('issue', 'labeled', 'mallory')), 'false', 'label on someone else\'s issue');
  assert.strictEqual(await ok(ev('issue', 'labeled', 'octo')), 'false', 'labeled, own issue');
  assert.strictEqual(await ok(ev('pull_request', 'opened', 'octo')), 'true', 'new pull request');
  assert.strictEqual(await ok(ev('pull_request', 'reopened', 'mallory')), 'false', 'reopened');
  assert.strictEqual(await ok(ev('pull_request', 'opened', 'mallory')), 'false', 'someone else\'s pull request');
  assert.strictEqual(await ok(ev('review', 'submitted', 'octo', { pull_request: { user: { login: 'mallory' } } })), 'true', 'own review on another PR');
  assert.strictEqual(await ok(ev('review', 'edited', 'octo')), 'false', 'edited review');
  assert.strictEqual(await ok(ev('discussion', 'created', 'octo')), 'true', 'new discussion');
  assert.strictEqual(await ok(ev('discussion', 'edited', 'mallory')), 'false', 'edited discussion');
  // A comment event also carries the issue: the comment decides.
  assert.strictEqual(await ok(ev('comment', 'created', 'octo', { issue: { user: { login: 'mallory' } } })), 'true', 'own comment on someone else\'s issue');
  assert.strictEqual(await ok(ev('comment', 'created', 'mallory', { issue: { user: { login: 'octo' } } })), 'false', 'someone else\'s comment on own issue');
  // push, schedule and manual runs carry none of these.
  assert.strictEqual(await ok({ sender: { type: 'User' } }), 'true', 'push');
});

