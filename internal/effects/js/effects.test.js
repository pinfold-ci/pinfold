test('artifact binding: accepts exactly the reported artifact', async () => {
  const d = 'a'.repeat(64);
  const env = { PINFOLD_NAME: 'dist', T_EXPECTED_ID: '123', T_EXPECTED_DIGEST: d };
  let seen;
  const { outputs } = await run('artifact_bind', env, { listArtifacts: (args) => { seen = args; return [{ id: 123, name: 'dist', digest: 'sha256:' + d }]; } });
  assert.deepStrictEqual(seen, { owner: 'o', repo: 'r', run_id: 99, name: 'dist', per_page: 100 });
  // The download step fetches by this id (pinfold#63), so a same-name artifact
  // uploaded after the check can't be what gets downloaded.
  assert.deepStrictEqual(outputs, { id: '123' });
});

test('artifact binding: rejects anything else', async () => {
  const d = 'a'.repeat(64);
  const env = { PINFOLD_NAME: 'dist', T_EXPECTED_ID: '123', T_EXPECTED_DIGEST: 'sha256:' + d };
  const one = (a) => ({ listArtifacts: () => a });
  await assert.rejects(run('artifact_bind', env, one([{ id: 124, name: 'dist', digest: d }])), /not the one/);
  await assert.rejects(run('artifact_bind', env, one([{ id: 123, name: 'dist', digest: 'b'.repeat(64) }])), /not the one/);
  await assert.rejects(run('artifact_bind', env, one([{ id: 123, name: 'dist', digest: null }])), /not the one/);
  await assert.rejects(run('artifact_bind', env, one([])), /found 0/);
  await assert.rejects(run('artifact_bind', env, one([{ id: 123, name: 'dist', digest: d }, { id: 5, name: 'dist', digest: d }])), /found 2/);
  await assert.rejects(run('artifact_bind', { ...env, T_EXPECTED_ID: '123 OR 1' }, one([])), /no valid artifact id/);
  await assert.rejects(run('artifact_bind', { ...env, T_EXPECTED_DIGEST: 'xyz' }, one([])), /no valid artifact digest/);
});
