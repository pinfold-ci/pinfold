// TestSanitizerProperties runs the JavaScript property tests with Node. CI
// runners have Node; locally the test is skipped if it isn't installed, unless
// PINFOLD_REQUIRE_NODE is set.
func TestSanitizerProperties(t *testing.T) {
	node, err := exec.LookPath("node")
	if err != nil {
		if os.Getenv("PINFOLD_REQUIRE_NODE") != "" || os.Getenv("CI") != "" {
			t.Fatal("node is required to test the effect sanitiser")
		}
		t.Skip("node not installed")
	}
	out, err := exec.Command(node, "--test", "js/sanitize.test.js", "js/effects.test.js").CombinedOutput() // #nosec G204 -- fixed test command
	if err != nil {
		t.Fatalf("sanitiser property tests failed:\n%s", out)
	}
	if !strings.Contains(string(out), "# fail 0") {
		t.Fatalf("unexpected node test output:\n%s", out)
	}
}

// TestScriptsAreSafeLiterals checks every assembled script: ASCII only (no
// invisible characters), no tabs (the emitter writes them as literal blocks),
// and no "${{", which GitHub would evaluate as an expression.
func TestScriptsAreSafeLiterals(t *testing.T) {
	scripts := Scripts()
	if len(scripts) != 7 {
		t.Fatalf("got %d scripts, want 7", len(scripts))
	}
	for name, s := range scripts {
		for i, r := range s {
			if r > 127 || r == '\t' {
				t.Fatalf("%s: character %U at byte %d", name, r, i)
			}
		}
		if strings.Contains(s, "${{") {
			t.Fatalf("%s contains ${{", name)
		}
		if !strings.HasPrefix(s, "// Generated by pinfold (effect "+name+")") {
			t.Errorf("%s: missing header", name)
		}
	}
	if _, err := Script("nope"); err == nil {
		t.Error("unknown effect: no error")
	}
}
