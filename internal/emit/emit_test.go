func TestScalarQuoting(t *testing.T) {
	tests := []struct{ in, want string }{
		{"ubuntu-24.04", "ubuntu-24.04"},
		{"actions/checkout@v7", "actions/checkout@v7"},
		{"python -m build", "python -m build"},
		{"on", "'on'"},
		{"Yes", "'Yes'"},
		{"null", "'null'"},
		{"0x10", "'0x10'"},
		{"1.0", "'1.0'"},
		{"2026-10-30", "'2026-10-30'"},
		{"v*", "'v*'"},
		{"*", "'*'"},
		{"&a", "'&a'"},
		{"a: b", "'a: b'"},
		{"a #b", "'a #b'"},
		{"it's", "'it''s'"},
		{"", "''"},
		{" lead", "' lead'"},
		{"trail ", "'trail '"},
		{".hidden", "'.hidden'"},
		{"tab\there", `"tab\there"`},
		{"nul\x00", `"nul\u0000"`},
	}
	for _, tt := range tests {
		if got := Scalar(tt.in); got != tt.want {
			t.Errorf("Scalar(%q) = %s, want %s", tt.in, got, tt.want)
		}
	}
}

func TestDocument(t *testing.T) {
	doc := Document([]string{"generated by pinfold", "do not edit"}, Map{
		{Key: "name", Value: Str("release")},
		{Key: "on", Value: Map{{Key: "push", Value: Map{{Key: "tags", Value: Seq{Str("v*")}}}}}},
		{Key: "permissions", Value: Empty{}},
		{Key: "jobs", Value: Map{{Key: "build", Value: Map{
			{Key: "runs-on", Value: Str("ubuntu-24.04")},
			{Key: "timeout-minutes", Value: Int(10)},
			{Key: "steps", Value: Seq{
				Map{{Key: "uses", Value: Str("actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1"), Comment: "v7.0.1"}, {Key: "with", Value: Map{{Key: "persist-credentials", Value: Bool(false)}}}},
				Map{{Key: "run", Value: Str("python -m pip install build\npython -m build\n")}},
			}},
		}}}},
	})
	want := `# generated by pinfold
# do not edit
name: release
'on':
  push:
    tags:
      - 'v*'
permissions: {}
jobs:
  build:
    runs-on: ubuntu-24.04
    timeout-minutes: 10
    steps:
      - uses: actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1
        with:
          persist-credentials: false
      - run: |
          python -m pip install build
          python -m build
`
	if doc != want {
		t.Errorf("Document =\n%s\nwant\n%s", doc, want)
	}
	if strings.Contains(doc, "\r") {
		t.Error("output contains CR")
	}
}

func TestCommentsCantBreakLines(t *testing.T) {
	doc := Document([]string{"a\rb"}, Map{{Key: "k", Value: Str("v"), Comment: "x\ny: injected"}})
	var out map[string]any
	if err := yaml.Unmarshal([]byte(doc), &out); err != nil {
		t.Fatalf("%v\n%s", err, doc)
	}
	if len(out) != 1 || out["k"] != "v" {
		t.Errorf("comment changed the document: %v\n%s", out, doc)
	}
}

// roundTrip emits s as a value (and as a key) and parses it back.
func roundTrip(t *testing.T, s string) {
	t.Helper()
	doc := Document(nil, Map{
		{Key: "v", Value: Str(s)},
		{Key: "nested", Value: Map{{Key: "list", Value: Seq{Str(s), Map{{Key: "run", Value: Str(s)}}}}}},
	})
	var root yaml.Node
	if err := yaml.Unmarshal([]byte(doc), &root); err != nil {
		t.Fatalf("emitted YAML doesn't parse for %q: %v\n%s", s, err, doc)
	}
	var out map[string]any
	if err := root.Decode(&out); err != nil {
		t.Fatalf("decode %q: %v\n%s", s, err, doc)
	}
	nested := out["nested"].(map[string]any)["list"].([]any)
	for _, got := range []any{out["v"], nested[0], nested[1].(map[string]any)["run"]} {
		if got != s {
			t.Fatalf("round trip of %q gave %#v\n%s", s, got, doc)
		}
	}
	if len(Scalar(s)) > MaxKey {
		return // keys this long are rejected by the spec; TestLongKeyPanics covers the emitter
	}
	keyDoc := Document(nil, Map{{Key: s, Value: Str("as key")}})
	var keyOut map[string]any
	if err := yaml.Unmarshal([]byte(keyDoc), &keyOut); err != nil || len(keyOut) != 1 || keyOut[s] != "as key" {
		t.Fatalf("key %q didn't round-trip (%v): %v\n%s", s, err, keyOut, keyDoc)
	}
	if strings.Contains(doc, "\r") {
		t.Fatalf("CR in output for %q", s)
	}
}

func TestRoundTripTable(t *testing.T) {
	for _, s := range []string{
		"", " ", "on", "off", "~", "-", "- x", "? x", "!tag", "%x", "@x", "`x", "|", ">", "#", "a:b", "a: b", "a #b",
		"line1\nline2", "line1\nline2\n", " lead\nx", "\nstart", "end\n\n", "tab\tin\nblock", "trail \nx",
		"\u2028", "\ufeff", "\ufffe", "x\uffff\ny", "é", "日本", "\"q\"", "'s'", "\\", "${{ x }}", "0o17", "1e3", "+1", ".5", ".inf", "1_000", "12:30",
	} {
		roundTrip(t, s)
	}
}

func TestLongKeyPanics(t *testing.T) {
	defer func() {
		if recover() == nil {
			t.Error("no panic for an over-long key")
		}
	}()
	Document(nil, Map{{Key: strings.Repeat("k", MaxKey+1), Value: Str("v")}})
}

func FuzzRoundTrip(f *testing.F) {
	for _, s := range []string{"x", "on", "a\nb\n", " lead", "'\"", "\x00"} {
		f.Add(s)
	}
	f.Fuzz(func(t *testing.T, s string) {
		if !utf8.ValidString(s) {
			t.Skip("invalid UTF-8 is escaped, not round-tripped")
		}
		roundTrip(t, s)
	})
}

