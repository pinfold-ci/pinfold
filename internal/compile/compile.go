// Package compile runs the whole pipeline: load, decode, graph checks,
// lowering, the GitHub adapter and the verifier. Nothing is returned for
// writing unless every stage passes.
package compile

import (
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/pinfold-ci/pinfold/internal/adapter/github"
	"github.com/pinfold-ci/pinfold/internal/diag"
	"github.com/pinfold-ci/pinfold/internal/effects"
	"github.com/pinfold-ci/pinfold/internal/graph"
	"github.com/pinfold-ci/pinfold/internal/ir"
	"github.com/pinfold-ci/pinfold/internal/load"
	"github.com/pinfold-ci/pinfold/internal/permissions"
	"github.com/pinfold-ci/pinfold/internal/spec"
	"github.com/pinfold-ci/pinfold/internal/taint"
	"github.com/pinfold-ci/pinfold/internal/verify"
	"github.com/pinfold-ci/pinfold/internal/zones"
)

// Result is a successful compilation.
type Result struct {
	Program *ir.Program
	Files   []github.File // paths relative to the spec's directory
}

// Front loads, decodes and graph-checks the spec at path, then lowers it. It
// also returns the normalised spec bytes it parsed, for the header hash.
func Front(path string) (*ir.Program, []byte, diag.List) {
	src, diags := load.Read(path)
	if diags.HasErrors() {
		return nil, nil, diags
	}
	root, diags := load.Load(path, src)
	if diags.HasErrors() {
		return nil, nil, diags
	}
	s, diags := spec.Decode(path, root)
	if diags.HasErrors() {
		return nil, nil, diags
	}
	_, more := graph.Check(s)
	diags = append(diags, more...)
	if diags.HasErrors() {
		diags.Sort()
		return nil, nil, diags
	}
	p := ir.Lower(s)
	diags = append(diags, zones.Check(s, p)...)
	diags = append(diags, taint.Check(s, p)...)
	diags = append(diags, permissions.Check(s, p)...)
	diags = append(diags, effects.Check(s)...)
	diags.Sort()
	if diags.HasErrors() {
		return nil, nil, diags
	}
	return p, load.Normalize(src), diags
}

// Run compiles the spec at path. Warnings may come back with a Result.
func Run(path string) (*Result, diag.List) {
	p, src, diags := Front(path)
	if p == nil {
		return nil, diags
	}
	sum := sha256.Sum256(src)
	files := github.Compile(p, specName(path), hex.EncodeToString(sum[:]))
	for i, f := range files {
		diags = append(diags, verify.Workflow(f.Path, f.Content, p.Workflows[i])...)
	}
	diags.Sort()
	if diags.HasErrors() {
		return nil, diags
	}
	return &Result{Program: p, Files: files}, diags
}

// specName is the spec's file name for the generated header, as the directory
// stores it rather than as it was typed: on a case-insensitive file system
// "PINFOLD.yml" opens pinfold.yml, and macOS may hand back a decomposed (NFD)
// spelling, which would change the generated bytes (#64).
func specName(path string) string {
	typed := filepath.Base(path)
	entries, err := os.ReadDir(filepath.Dir(path))
	if err != nil {
		return typed
	}
	want, err := os.Stat(path)
	if err != nil {
		return typed
	}
	names := make([]string, 0, len(entries))
	for _, e := range entries {
		names = append(names, e.Name())
	}
	return storedName(typed, names, func(name string) bool {
		fi, err := os.Stat(filepath.Join(filepath.Dir(path), name))
		return err == nil && os.SameFile(fi, want)
	})
}

// storedName picks the directory entry that is the typed file: the typed name
// itself when the directory has it, else the one entry that is the same file.
func storedName(typed string, entries []string, same func(string) bool) string {
	if slices.Contains(entries, typed) {
		return typed
	}
	var found []string
	for _, e := range entries {
		if same(e) {
			found = append(found, e)
		}
	}
	if len(found) == 1 {
		return found[0]
	}
	return typed
}

// Drift compares the result with the files on disk under dir and returns the
// paths that are missing or differ.
func Drift(dir string, r *Result) ([]string, error) {
	var out []string
	for _, f := range r.Files {
		got, err := os.ReadFile(filepath.Join(dir, f.Path)) // #nosec G304 -- paths are compiler-generated
		if os.IsNotExist(err) {
			out = append(out, f.Path+" (missing)")
			continue
		}
		if err != nil {
			return nil, err
		}
		if string(load.Normalize(got)) != f.Content {
			out = append(out, f.Path)
		}
	}
	return out, nil
}

// Write writes the result's files under dir. It never follows a symlink
// below dir: a branch can commit .github/workflows/pinfold-*.yml, or a
// directory on the way, as a link to a file elsewhere, and running the
// compiler on that branch must not write through it (Mythos audit I1). Each
// file is written to a temporary file and renamed into place.
func Write(dir string, r *Result) error {
	for _, f := range r.Files {
		if err := writeFile(dir, f.Path, []byte(f.Content)); err != nil {
			return fmt.Errorf("writing %s: %w", f.Path, err)
		}
	}
	return nil
}

func writeFile(dir, rel string, content []byte) error {
	parts := strings.Split(filepath.ToSlash(filepath.Clean(rel)), "/")
	if filepath.IsAbs(rel) || slices.Contains(parts, "..") {
		return fmt.Errorf("path escapes the spec's directory")
	}
	// Create or check each directory below dir without following links.
	cur := dir
	for _, part := range parts[:len(parts)-1] {
		cur = filepath.Join(cur, part)
		fi, err := os.Lstat(cur)
		switch {
		case os.IsNotExist(err):
			if err := os.Mkdir(cur, 0o755); err != nil { // #nosec G301 -- workflow directories are normal repo directories
				return err
			}
		case err != nil:
			return err
		case fi.Mode()&os.ModeSymlink != 0:
			return fmt.Errorf("%s is a symbolic link; Pinfold doesn't write through links (remove it and compile again)", cur)
		case !fi.IsDir():
			return fmt.Errorf("%s isn't a directory", cur)
		}
	}
	target := filepath.Join(cur, parts[len(parts)-1])
	if fi, err := os.Lstat(target); err == nil && !fi.Mode().IsRegular() {
		return fmt.Errorf("%s isn't a regular file (a symbolic link?); Pinfold doesn't write through links (remove it and compile again)", target)
	} else if err != nil && !os.IsNotExist(err) {
		return err
	}
	tmp, err := os.CreateTemp(cur, ".pinfold-*.tmp")
	if err != nil {
		return err
	}
	defer func() { _ = os.Remove(tmp.Name()) }() // no-op after a successful rename
	if _, err := tmp.Write(content); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Chmod(0o644); err != nil { // #nosec G302 -- workflows are normal, readable repo files
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	// rename replaces the directory entry itself; it never follows a link.
	return os.Rename(tmp.Name(), target)
}
